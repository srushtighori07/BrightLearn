/* =========================================================
   LANGUAGE CHANGE
   ========================================================= */

function changeLanguage(language) {

    currentLanguage = language;

    localStorage.setItem(
        "brightLearnLanguage",
        language
    );

    const texts = translations[language] || translations.en;

    document.querySelectorAll("[data-i18n]").forEach(function (element) {

        const key = element.getAttribute("data-i18n");

        if (texts[key]) {
            element.textContent = texts[key];
        }

    });


    document.querySelectorAll("[data-i18n-placeholder]").forEach(function (element) {

        const key = element.getAttribute("data-i18n-placeholder");

        if (texts[key]) {
            element.placeholder = texts[key];
        }

    });


    const selector = document.getElementById("language-selector");

    if (selector) {
        selector.value = language;
    }


    updateDashboard();

    loadProfile();

}


/* =========================================================
   TRANSLATION HELPER
   ========================================================= */

function getTranslation(key) {

    const languageData =
        translations[currentLanguage] || translations.en;

    return languageData[key] || translations.en[key] || key;

}


/* =========================================================
   COURSE → QUIZ
   ========================================================= */

function startCourse(subject) {

    const selector =
        document.getElementById("quiz-subject");

    if (selector) {

        selector.value = subject;

        showSelectedQuiz(subject);

    }

    const quizSection =
        document.getElementById("quiz");

    if (quizSection) {

        quizSection.scrollIntoView({
            behavior: "smooth"
        });

    }

}


/* =========================================================
   SHOW SELECTED QUIZ
   ========================================================= */

function showSelectedQuiz(subject) {

    const quizSections =
        document.querySelectorAll(".quiz-subject");

    quizSections.forEach(function (section) {

        section.style.display = "none";

    });


    if (!subject) {
        return;
    }


    const selectedQuiz =
        document.getElementById("quiz-" + subject);

    if (selectedQuiz) {

        selectedQuiz.style.display = "block";

    }

}


/* =========================================================
   SUBMIT QUIZ
   ========================================================= */

function submitQuiz(subject) {

    const questions =
        quizData[subject];

    if (!questions) {
        return;
    }


    let score = 0;

    let allAnswered = true;


    questions.forEach(function (question, index) {

        const selected =
            document.querySelector(
                `input[name="${subject}-q${index}"]:checked`
            );


        if (!selected) {

            allAnswered = false;

        } else {

            if (
                Number(selected.value) ===
                question.answer
            ) {

                score++;

            }

        }

    });


    const resultElement =
        document.getElementById("quiz-result");


    if (!allAnswered) {

        resultElement.textContent =
            getTranslation("answerAll");

        resultElement.style.color = "#a35d6f";

        return;

    }


    quizProgress[subject] = {
        completed: true,
        score: score,
        total: 15
    };


    localStorage.setItem(
        progressKey,
        JSON.stringify(quizProgress)
    );


    resultElement.textContent =
        `${getTranslation("quizResult")} ${score} ${getTranslation("outOf")} 15. ${getTranslation("quizCompleted")}`;


    resultElement.style.color = "#4d875c";


    updateDashboard();

}


/* =========================================================
   DASHBOARD UPDATE
   ========================================================= */

function updateDashboard() {

    const subjects = [
        "cs",
        "math",
        "science",
        "communication"
    ];


    let completedCount = 0;


    subjects.forEach(function (subject) {

        if (
            quizProgress[subject] &&
            quizProgress[subject].completed
        ) {

            completedCount++;

        }

    });


    const percentage =
        Math.round(
            (completedCount / subjects.length) * 100
        );


    const completedElement =
        document.getElementById("completed-count");

    if (completedElement) {

        completedElement.textContent =
            `${completedCount} / 4`;

    }


    const progressPercent =
        document.getElementById("progress-percent");

    if (progressPercent) {

        progressPercent.textContent =
            `${percentage}%`;

    }


    const progressFill =
        document.getElementById("progress-fill");

    if (progressFill) {

        progressFill.style.width =
            `${percentage}%`;

    }


    const progressText =
        document.getElementById("progress-text");

    if (progressText) {

        progressText.textContent =
            percentage === 100
                ? getTranslation("excellentProgress")
                : getTranslation("progressText");

    }


    const achievement =
        document.getElementById("achievement-text");

    if (achievement) {

        if (percentage === 100) {

            achievement.textContent =
                getTranslation("excellentProgress");

        } else if (percentage >= 50) {

            achievement.textContent =
                "⭐ Great progress!";

        } else {

            achievement.textContent =
                getTranslation("keepLearning");

        }

    }


    updateCourseProgress(
        "cs",
        "course-progress-cs",
        "course-percent-cs"
    );

    updateCourseProgress(
        "math",
        "course-progress-math",
        "course-percent-math"
    );

    updateCourseProgress(
        "science",
        "course-progress-science",
        "course-percent-science"
    );

    updateCourseProgress(
        "communication",
        "course-progress-communication",
        "course-percent-communication"
    );


    updateTaskStatus(
        "cs",
        "status-cs"
    );

    updateTaskStatus(
        "math",
        "status-math"
    );

    updateTaskStatus(
        "science",
        "status-science"
    );

    updateTaskStatus(
        "communication",
        "status-communication"
    );

}


/* =========================================================
   COURSE PROGRESS
   ========================================================= */

function updateCourseProgress(
    subject,
    progressId,
    percentId
) {

    const progress =
        quizProgress[subject];

    const percentage =
        progress && progress.completed
            ? 100
            : 0;


    const progressBar =
        document.getElementById(progressId);

    const percentText =
        document.getElementById(percentId);


    if (progressBar) {

        progressBar.style.width =
            `${percentage}%`;

    }


    if (percentText) {

        percentText.textContent =
            `${percentage}%`;

    }

}


/* =========================================================
   DASHBOARD TASK STATUS
   ========================================================= */

function updateTaskStatus(
    subject,
    statusId
) {

    const status =
        document.getElementById(statusId);

    if (!status) {
        return;
    }


    const completed =
        quizProgress[subject] &&
        quizProgress[subject].completed;


    status.textContent =
        completed
            ? getTranslation("completed")
            : getTranslation("pending");


    status.classList.remove(
        "completed",
        "pending"
    );


    status.classList.add(
        completed
            ? "completed"
            : "pending"
    );


    const taskItem =
        status.closest(".task-item");


    if (taskItem) {

        taskItem.classList.toggle(
            "task-completed",
            completed
        );

    }

}


