/* =========================================================
   OPTIONAL: GENERATE QUIZ QUESTIONS
   This function can be called if the HTML uses empty
   quiz containers.
   ========================================================= */

function generateQuizHTML(subject) {

    const questions =
        quizData[subject];


    const container =
        document.getElementById(
            "quiz-" + subject
        );


    if (!container || !questions) {
        return;
    }


    let html = `<h3>${getTranslation(subject === "cs"
        ? "computerScience"
        : subject === "math"
            ? "mathematics"
            : subject === "science"
                ? "science"
                : "communication")}</h3>`;


    questions.forEach(
        function (question, index) {

            html += `
                <div class="question">

                    <p>
                        ${index + 1}. ${question.question}
                    </p>
            `;


            question.options.forEach(
                function (option, optionIndex) {

                    html += `
                        <label>
                            <input
                                type="radio"
                                name="${subject}-q${index}"
                                value="${optionIndex}"
                            >
                            ${option}
                        </label>
                    `;

                }
            );


            html += `
                </div>
            `;

        }
    );


    html += `
        <button
            type="button"
            class="btn"
            onclick="submitQuiz('${subject}')"
        >
            ${getTranslation("submitQuiz")}
        </button>
    `;


    container.innerHTML = html;

}


/* =========================================================
   INITIALIZE QUIZZES IF CONTAINERS ARE EMPTY
   ========================================================= */

function initializeQuizzes() {

    const subjects = [
        "cs",
        "math",
        "science",
        "communication"
    ];


    subjects.forEach(
        function (subject) {

            const container =
                document.getElementById(
                    "quiz-" + subject
                );


            if (
                container &&
                container.children.length === 0
            ) {

                generateQuizHTML(subject);

            }

        }
    );

}


